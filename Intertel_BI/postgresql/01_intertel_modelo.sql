-- Intertel BI | Fase 1 | PostgreSQL 10+
-- Ejecutar conectado a una base vacía denominada intertel_bi.
-- No contiene datos personales ni carga datos de negocio.
BEGIN;
CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS dw;
CREATE SCHEMA IF NOT EXISTS audit;

-- Staging: valores de origen como texto; Pentaho realiza conversiones.
-- Cargar solo hojas principales. fila_origen es la fila física de Excel (1-based).
CREATE TABLE IF NOT EXISTS staging.clientes (
    fila_origen integer PRIMARY KEY CHECK (fila_origen > 0),
    codigo text, nombre text, ruc text
);
CREATE TABLE IF NOT EXISTS staging.facturacion (
    fila_origen integer PRIMARY KEY CHECK (fila_origen > 0),
    numero_factura text, nombre text, total text, fecha text
);
CREATE TABLE IF NOT EXISTS staging.dispositivos (
    fila_origen integer PRIMARY KEY CHECK (fila_origen > 0),
    dispositivo text, grupo text, numero_sim text, hora text,
    posicion text, velocidad text, altitud text, angulo text,
    duracion text, distancia text, odometro text, horas_motor text
);

-- Auditoría: trazabilidad de ejecuciones y excepciones sin copiar PII.
CREATE TABLE IF NOT EXISTS audit.ejecucion_etl (
    ejecucion_sk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inicio timestamp with time zone NOT NULL DEFAULT now(),
    fin timestamp with time zone,
    estado text NOT NULL DEFAULT 'EN_PROCESO'
        CHECK (estado IN ('EN_PROCESO','EXITOSO','ERROR')),
    observacion text
);
CREATE TABLE IF NOT EXISTS audit.incidencia_etl (
    incidencia_sk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ejecucion_sk bigint REFERENCES audit.ejecucion_etl(ejecucion_sk),
    fuente text NOT NULL,
    fila_origen integer,
    regla text NOT NULL,
    severidad text NOT NULL CHECK (severidad IN ('ADVERTENCIA','RECHAZO')),
    detalle text,
    registrada_en timestamp with time zone NOT NULL DEFAULT now()
);

-- Dimensiones: se cargarán en Pentaho. Fecha SK en formato AAAAMMDD.
CREATE TABLE IF NOT EXISTS dw.dim_fecha (
    fecha_sk integer PRIMARY KEY,
    fecha date NOT NULL UNIQUE,
    anio smallint NOT NULL,
    trimestre smallint NOT NULL CHECK (trimestre BETWEEN 1 AND 4),
    mes smallint NOT NULL CHECK (mes BETWEEN 1 AND 12),
    nombre_mes varchar(12) NOT NULL,
    dia smallint NOT NULL CHECK (dia BETWEEN 1 AND 31),
    dia_semana smallint NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
    nombre_dia varchar(12) NOT NULL,
    CHECK (fecha_sk = anio * 10000 + mes * 100 + dia),
    CHECK (anio = EXTRACT(YEAR FROM fecha) AND trimestre = EXTRACT(QUARTER FROM fecha)
       AND mes = EXTRACT(MONTH FROM fecha) AND dia = EXTRACT(DAY FROM fecha)
       AND dia_semana = EXTRACT(ISODOW FROM fecha))
);

-- Grano: etiqueta normalizada de cliente, NO identidad legal verificada.
-- No se propagan RUC ni códigos arbitrariamente cuando hay coincidencias múltiples.
CREATE TABLE IF NOT EXISTS dw.dim_cliente (
    cliente_sk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_normalizado text NOT NULL UNIQUE CHECK (btrim(nombre_normalizado) <> ''),
    codigo_origen text,
    coincidencias_catalogo integer NOT NULL CHECK (coincidencias_catalogo >= 0),
    estado_catalogo text NOT NULL CHECK (estado_catalogo IN
       ('SIN_COINCIDENCIA','COINCIDENCIA_UNICA','COINCIDENCIA_MULTIPLE')),
    CHECK ((coincidencias_catalogo = 0 AND estado_catalogo = 'SIN_COINCIDENCIA') OR
           (coincidencias_catalogo = 1 AND estado_catalogo = 'COINCIDENCIA_UNICA') OR
           (coincidencias_catalogo > 1 AND estado_catalogo = 'COINCIDENCIA_MULTIPLE')),
    CHECK (codigo_origen IS NULL OR coincidencias_catalogo = 1)
);
CREATE TABLE IF NOT EXISTS dw.dim_grupo (
    grupo_sk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave_grupo text NOT NULL UNIQUE,
    nombre_grupo text NOT NULL,
    es_sin_grupo boolean NOT NULL DEFAULT false
);

-- Clave provisional en Pentaho: nombre normalizado + SIM si existe (hash local
-- con secreto si se quiere evitar exponer SIM); casos ambiguos sin SIM: clave
-- por reporte/fila y marcar identidad provisional. No asumir que SIM es inmutable.
CREATE TABLE IF NOT EXISTS dw.dim_dispositivo (
    dispositivo_sk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave_origen text NOT NULL UNIQUE,
    nombre_dispositivo text NOT NULL,
    tiene_sim boolean NOT NULL,
    identidad_provisional boolean NOT NULL DEFAULT true
);

-- Hechos: la clave de origen de la factura es única en la hoja examinada.
-- No se deduce ningún producto/plan ni estado de pago.
CREATE TABLE IF NOT EXISTS dw.fact_facturacion (
    facturacion_sk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_sk bigint NOT NULL REFERENCES dw.dim_cliente(cliente_sk),
    fecha_sk integer NOT NULL REFERENCES dw.dim_fecha(fecha_sk),
    numero_factura text NOT NULL UNIQUE CHECK (btrim(numero_factura) <> ''),
    valor_facturado numeric(14,2) NOT NULL,
    cantidad_facturas smallint NOT NULL DEFAULT 1 CHECK (cantidad_facturas = 1),
    fila_origen integer NOT NULL CHECK (fila_origen > 0)
);

-- Grano: una fila del reporte para una fecha de extracción; no equivale
-- necesariamente a un vehículo único o a una desconexión confirmada.
-- Se admite un reporte principal por fecha. Nueva versión del mismo día:
-- reemplazar la instantánea completa tras validación, no anexarla.
CREATE TABLE IF NOT EXISTS dw.fact_estado_gps (
    estado_gps_sk bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispositivo_sk bigint NOT NULL REFERENCES dw.dim_dispositivo(dispositivo_sk),
    grupo_sk bigint NOT NULL REFERENCES dw.dim_grupo(grupo_sk),
    fecha_reporte_sk integer NOT NULL REFERENCES dw.dim_fecha(fecha_sk),
    fecha_registro_sk integer REFERENCES dw.dim_fecha(fecha_sk),
    ultimo_registro timestamp without time zone,
    estado_datos text NOT NULL CHECK (estado_datos IN
        ('CON_DATOS','SIN_DATOS','FECHA_INVALIDA')),
    dias_sin_registro integer CHECK (dias_sin_registro >= 0),
    tiene_posicion boolean NOT NULL DEFAULT false,
    distancia_km numeric(16,3) CHECK (distancia_km >= 0),
    cantidad_registros smallint NOT NULL DEFAULT 1 CHECK (cantidad_registros = 1),
    fila_origen integer NOT NULL CHECK (fila_origen > 0),
    UNIQUE (fecha_reporte_sk, fila_origen),
    CHECK ((estado_datos = 'CON_DATOS' AND fecha_registro_sk IS NOT NULL
            AND ultimo_registro IS NOT NULL AND dias_sin_registro IS NOT NULL)
           OR (estado_datos <> 'CON_DATOS' AND fecha_registro_sk IS NULL
            AND ultimo_registro IS NULL AND dias_sin_registro IS NULL)),
    CHECK (fecha_registro_sk IS NULL OR fecha_registro_sk <= fecha_reporte_sk),
    CHECK (ultimo_registro IS NULL OR fecha_registro_sk =
       EXTRACT(YEAR FROM ultimo_registro)::integer * 10000 +
       EXTRACT(MONTH FROM ultimo_registro)::integer * 100 +
       EXTRACT(DAY FROM ultimo_registro)::integer)
);

CREATE INDEX IF NOT EXISTS ix_fact_facturacion_fecha ON dw.fact_facturacion(fecha_sk);
CREATE INDEX IF NOT EXISTS ix_fact_facturacion_cliente ON dw.fact_facturacion(cliente_sk);
CREATE INDEX IF NOT EXISTS ix_fact_gps_dispositivo ON dw.fact_estado_gps(dispositivo_sk);
CREATE INDEX IF NOT EXISTS ix_fact_gps_grupo ON dw.fact_estado_gps(grupo_sk);
CREATE INDEX IF NOT EXISTS ix_fact_gps_fecha_registro ON dw.fact_estado_gps(fecha_registro_sk);

COMMENT ON TABLE dw.dim_cliente IS 'Etiquetas de facturación normalizadas; coincidencias provisionales por nombre.';
COMMENT ON TABLE dw.fact_facturacion IS 'Una fila por código de factura en la fuente autorizada; valor facturado, no cobrado.';
COMMENT ON TABLE dw.fact_estado_gps IS 'Una fila por registro del reporte y fecha de extracción; alcance del reporte por confirmar.';
COMMENT ON COLUMN dw.fact_estado_gps.distancia_km IS 'Distancia reportada; significado pendiente de confirmar. No sumar entre instantáneas.';
COMMENT ON COLUMN dw.fact_estado_gps.dias_sin_registro IS 'Diferencia de fechas calendario entre el reporte y el último registro, no duración de desconexión.';
COMMIT;
